"""Generate the EU reference snapshot and SQL seed from the supplied workbook."""
from __future__ import annotations

import hashlib
import json
from collections import defaultdict
from pathlib import Path
from typing import Sequence

from openpyxl import load_workbook

from autarch.capex.demo_v2_asset_classes import AssetClassEntry, AssetClassMaster


_GENERATED_HEADER = "-- Generated by tools/generate_capex_eu_asset_classes.py; source rows are not invented.\n"
_MAX_BATCH_CHARACTERS = 60_000


def _sql_catalog_declaration(catalog_json: str) -> str:
    statements = ["DECLARE @Catalog nvarchar(max) = N'';"]
    for offset in range(0, len(catalog_json), 1000):
        fragment = catalog_json[offset:offset + 1000].replace("'", "''")
        statements.append(f"SET @Catalog += N'{fragment}';")
    checksum = hashlib.sha256(catalog_json.encode("utf-16le")).hexdigest()
    statements.extend([
        f"IF ISJSON(@Catalog) <> 1 OR HASHBYTES('SHA2_256', @Catalog) <> 0x{checksum}",
        "    THROW 51283, 'EU catalog is incomplete or changed. Run the entire generated SQL file.', 1;",
    ])
    return "\n".join(statements) + "\n"


def _seed_sql(master: AssetClassMaster, classes: Sequence[AssetClassEntry]) -> str:
    payload = master.model_copy(update={"classes": list(classes)}).model_dump(mode="json", by_alias=True)
    encoded = json.dumps(payload, ensure_ascii=True, separators=(",", ":"))
    allowed_codes = ", ".join("N'" + item.asset_class_code.replace("'", "''") + "'" for item in master.classes)
    return (
        _GENERATED_HEADER
        + "-- Web editors: run numbered files from 006_eu_asset_class_batches separately.\n"
        "SET NOCOUNT ON;\nSET XACT_ABORT ON;\n"
        "IF DB_NAME() <> N'cict-ai-cus-sqldb' OR @@TRANCOUNT <> 0\n"
        " THROW 51284, 'Use cict-ai-cus-sqldb outside an existing transaction.', 1;\n"
        "IF OBJECT_ID(N'ref.assetClassMaster', N'U') IS NULL\n"
        " THROW 51280, 'Apply migration 015 before seeding EU asset classes.', 1;\n"
        f"{_sql_catalog_declaration(encoded)}"
        "BEGIN TRY\n BEGIN TRANSACTION;\n"
        " IF EXISTS (SELECT 1 FROM ref.assetClassMaster WITH (UPDLOCK, HOLDLOCK)\n"
        f" WHERE AssetClassCode NOT IN ({allowed_codes})\n"
        " OR SourceSha256<>JSON_VALUE(@Catalog,'$.sourceSha256')\n"
        " OR SourceFile<>JSON_VALUE(@Catalog,'$.sourceFile')\n"
        " OR SourceSheet<>JSON_VALUE(@Catalog,'$.sourceSheet'))\n"
        "  THROW 51281, 'Existing EU catalog differs; review before replacing reference data.', 1;\n"
        " INSERT INTO ref.assetClassMaster\n"
        " (AssetClassCode, AssetClassName, AccountGroup, AccountMappingsJson, SourceFile, SourceSheet, SourceSha256)\n"
        " SELECT c.AssetClassCode, c.AssetClassName, c.AccountGroup, c.AccountMappingsJson,\n"
        " JSON_VALUE(@Catalog,'$.sourceFile'), JSON_VALUE(@Catalog,'$.sourceSheet'),\n"
        " JSON_VALUE(@Catalog,'$.sourceSha256')\n"
        " FROM OPENJSON(@Catalog,'$.classes') WITH (\n"
        " AssetClassCode nvarchar(128) '$.assetClassCode', AssetClassName nvarchar(2000) '$.assetClassName',\n"
        " AccountGroup nvarchar(256) '$.accountGroup', AccountMappingsJson nvarchar(max) '$.accountMappings' AS JSON) c\n"
        " WHERE NOT EXISTS (SELECT 1 FROM ref.assetClassMaster m WHERE m.AssetClassCode=c.AssetClassCode);\n"
        " IF EXISTS (SELECT 1 FROM OPENJSON(@Catalog,'$.classes') WITH (\n"
        " AssetClassCode nvarchar(128) '$.assetClassCode', AssetClassName nvarchar(2000) '$.assetClassName',\n"
        " AccountGroup nvarchar(256) '$.accountGroup', AccountMappingsJson nvarchar(max) '$.accountMappings' AS JSON) c\n"
        " LEFT JOIN ref.assetClassMaster m ON m.AssetClassCode=c.AssetClassCode\n"
        " WHERE m.AssetClassCode IS NULL OR m.AssetClassName<>c.AssetClassName OR m.AccountGroup<>c.AccountGroup\n"
        " OR m.AccountMappingsJson COLLATE Latin1_General_100_BIN2<>c.AccountMappingsJson COLLATE Latin1_General_100_BIN2)\n"
        "  THROW 51282, 'EU catalog contents differ from the workbook. This batch was rolled back.', 1;\n"
        " COMMIT TRANSACTION;\n"
        f" SELECT {len(classes)} AS VerifiedBatchClasses, COUNT(*) AS AssetClassesSoFar\n"
        " FROM ref.assetClassMaster;\n"
        "END TRY\nBEGIN CATCH\n IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;\n THROW;\nEND CATCH;\n"
    )


def _verification_sql(master: AssetClassMaster) -> str:
    rows = []
    for item in master.classes:
        mappings = json.dumps(
            item.model_dump(mode="json", by_alias=True)["accountMappings"],
            ensure_ascii=True, separators=(",", ":"),
        )
        hashes = [hashlib.sha256(value.encode("utf-16le")).hexdigest()
                  for value in (item.asset_class_name, item.account_group, mappings)]
        code = item.asset_class_code.replace("'", "''")
        rows.append(f"(N'{code}', " + ", ".join("0x" + value for value in hashes) + ")")
    values = ",\n".join(rows)
    return (
        _GENERATED_HEADER
        + "SET NOCOUNT ON;\n"
        "IF DB_NAME() <> N'cict-ai-cus-sqldb'\n"
        " THROW 51284, 'Use cict-ai-cus-sqldb.', 1;\n"
        "DECLARE @Expected TABLE (AssetClassCode nvarchar(128) NOT NULL PRIMARY KEY,\n"
        " NameHash binary(32) NOT NULL, GroupHash binary(32) NOT NULL, MappingsHash binary(32) NOT NULL);\n"
        f"INSERT INTO @Expected VALUES\n{values};\n"
        f"IF (SELECT COUNT_BIG(*) FROM ref.assetClassMaster)<>{len(master.classes)} OR EXISTS (\n"
        " SELECT 1 FROM @Expected e LEFT JOIN ref.assetClassMaster m ON m.AssetClassCode=e.AssetClassCode\n"
        f" WHERE m.AssetClassCode IS NULL OR m.SourceSha256<>'{master.source_sha256}'\n"
        f" OR m.SourceFile<>N'{master.source_file.replace(chr(39), chr(39) * 2)}'\n"
        f" OR m.SourceSheet<>N'{master.source_sheet.replace(chr(39), chr(39) * 2)}'\n"
        " OR HASHBYTES('SHA2_256',m.AssetClassName)<>e.NameHash\n"
        " OR HASHBYTES('SHA2_256',m.AccountGroup)<>e.GroupHash\n"
        " OR HASHBYTES('SHA2_256',m.AccountMappingsJson)<>e.MappingsHash)\n"
        " THROW 51285, 'EU catalog is incomplete or changed. Run all small seed batches before ADF.', 1;\n"
        "SELECT 'EU_ASSET_CLASS_CATALOG_VERIFIED' AS Result, COUNT_BIG(*) AS AssetClasses,\n"
        " (SELECT COUNT_BIG(*) FROM ref.assetClassMaster a CROSS APPLY OPENJSON(a.AccountMappingsJson)) AS AccountMappings\n"
        "FROM ref.assetClassMaster;\n"
    )


def _small_seed_batches(master: AssetClassMaster) -> list[str]:
    batches = []
    pending: list[AssetClassEntry] = []
    for item in master.classes:
        candidate = _seed_sql(master, [*pending, item])
        if len(candidate.encode("utf-16le")) // 2 > _MAX_BATCH_CHARACTERS:
            if not pending:
                raise ValueError(f"EU class {item.asset_class_code} exceeds the safe SQL batch size.")
            batches.append(_seed_sql(master, pending))
            pending = []
        pending.append(item)
        if len(_seed_sql(master, pending).encode("utf-16le")) // 2 > _MAX_BATCH_CHARACTERS:
            raise ValueError(f"EU class {item.asset_class_code} exceeds the safe SQL batch size.")
    if pending:
        batches.append(_seed_sql(master, pending))
    return batches


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    source = root / "examples" / "data" / "capex" / "Asset classes EU.xlsx"
    workbook = load_workbook(source, read_only=True, data_only=True)
    grouped = defaultdict(list)
    try:
        sheet = workbook["Sheet2"]
        expected = ("Object Account", "Sub account", "Asset class",
                    "Account name", "Account group", "Account description")
        if next(sheet.iter_rows(values_only=True)) != expected:
            raise ValueError("Unexpected EU workbook column contract.")
        for row_number, row in enumerate(sheet.iter_rows(min_row=2, values_only=True), 2):
            account, sub, code, name, group, description = row
            if not isinstance(code, int) or not isinstance(account, int) \
                    or not all(isinstance(value, str) and value.strip() for value in (sub, name, group)):
                raise ValueError(f"Invalid EU source row {row_number}; no rows were silently skipped.")
            grouped[str(code)].append({
                "sourceRow": row_number, "objectAccount": account, "subAccount": sub,
                "accountName": name, "accountGroup": group,
                "accountDescription": description or "",
            })
    finally:
        workbook.close()
    classes = []
    for code, mappings in sorted(grouped.items()):
        groups = {item["accountGroup"].strip() for item in mappings}
        if len(groups) != 1:
            raise ValueError(f"Asset class {code} has conflicting account groups.")
        classes.append({
            "assetClassCode": code,
            "assetClassName": " | ".join(sorted({item["accountName"].strip() for item in mappings})),
            "accountGroup": groups.pop(), "accountMappings": mappings,
        })
    master = AssetClassMaster.model_validate({
        "sourceFile": source.name, "sourceSheet": "Sheet2",
        "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(), "classes": classes,
    })
    payload = master.model_dump(mode="json", by_alias=True)
    snapshot = root / "examples" / "data" / "capex" / "reference-v2" / "asset-class-master-eu-v1.json"
    snapshot.write_text(json.dumps(payload, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
    seed = root / "sql" / "data" / "006_seed_eu_asset_class_master.sql"
    seed.write_text(_seed_sql(master, master.classes), encoding="utf-8")
    batch_dir = seed.parent / "006_eu_asset_class_batches"
    batch_dir.mkdir(exist_ok=True)
    batch_files = {
        f"{index:03d}_seed_eu_asset_classes.sql": sql
        for index, sql in enumerate(_small_seed_batches(master), 1)
    }
    verification = _verification_sql(master)
    if len(verification.encode("utf-16le")) // 2 > _MAX_BATCH_CHARACTERS:
        raise ValueError("EU catalog verification exceeds the safe SQL batch size.")
    batch_files["999_verify_eu_asset_classes.sql"] = verification
    for path in batch_dir.glob("[0-9][0-9][0-9]_seed_eu_asset_classes.sql"):
        if path.name not in batch_files:
            if not path.read_text(encoding="utf-8").startswith(_GENERATED_HEADER):
                raise ValueError(f"Refusing to remove an unmanaged stale SQL file: {path.name}")
            path.unlink()
    for name, sql in batch_files.items():
        (batch_dir / name).write_text(sql, encoding="utf-8", newline="\n")
    print(json.dumps({"classes": len(classes), "sourceMappings": sum(map(len, grouped.values())),
                      "sourceSha256": master.source_sha256, "smallSeedBatches": len(batch_files) - 1}))


if __name__ == "__main__":
    main()
